def validate_ollama_model_name(name: str) -> str | None:
    """Returns an error string if the model name is invalid, or None if valid."""
    name = name.strip()
    if not name:
        return "モデル名を入力してください"
    if not _NAME_RE.match(name.lower()):
        return f"Ollama のモデル名に使えない文字があります: '{name}'（英小文字・数字・. _ - / : のみ）"
    return None


def clean_show_modelfile(show_text: str, base_model_name: str) -> str:
    """Cleans up the output of `ollama show <model> --modelfile`.

    - Strips the top comments added by 'ollama show'.
    - Replaces the raw blob path in 'FROM <blob>' with 'FROM <base_model_name>'.
    """
    lines = show_text.splitlines()
    # Strip leading comment block generated by ollama show
    start_idx = 0
    while start_idx < len(lines):
        line = lines[start_idx].strip()
        if line.startswith("# Modelfile generated by") or line.startswith("# To build a new Modelfile") or (line.startswith("# FROM ") and start_idx < 5):
            start_idx += 1
        elif not line and start_idx < 5:
            start_idx += 1
        else:
            break

    cleaned_lines = []
    replaced_from = False
    for line in lines[start_idx:]:
        stripped = line.strip()
        if not replaced_from and stripped.startswith("FROM "):
            cleaned_lines.append(f"FROM {base_model_name}")
            replaced_from = True
        else:
            cleaned_lines.append(line)

    if not replaced_from:
        cleaned_lines.insert(0, f"FROM {base_model_name}")

    return "\n".join(cleaned_lines).strip() + "\n"


def build_modelfile(
    from_model: str,
    system: str = "",
    parameters: list[tuple[str, str]] | dict[str, Any] | None = None,
    template: str = "",
    extra: str = "",
) -> str:
    """Builds a Modelfile text from individual sections."""
    lines: list[str] = [f"FROM {from_model.strip()}"]

    if template.strip():
        tpl = template.strip()
        if '"""' in tpl:
            lines.append(f"TEMPLATE {tpl}")
        else:
            lines.append(f'TEMPLATE """{tpl}"""')

    if system.strip():
        sys_text = system.strip()
        if '"""' in sys_text:
            lines.append(f"SYSTEM {sys_text}")
        else:
            lines.append(f'SYSTEM """{sys_text}"""')

    if parameters:
        param_items: list[tuple[str, str]]
        if isinstance(parameters, dict):
            param_items = [(str(k), str(v)) for k, v in parameters.items()]
        else:
            param_items = parameters
        for k, v in param_items:
            k_clean = str(k).strip()
            v_clean = str(v).strip()
            if k_clean and v_clean:
                lines.append(f"PARAMETER {k_clean} {v_clean}")

    if extra.strip():
        lines.append(extra.strip())

    return "\n".join(lines).strip() + "\n"


def parse_modelfile_sections(text: str) -> dict[str, Any]:
    """Extracts from_model, system, template, parameters, and extra lines from Modelfile text."""
    from_model = ""
    system = ""
    template = ""
    parameters: list[tuple[str, str]] = []
    extra_lines: list[str] = []

    lines = text.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        stripped = line.strip()

        if stripped.startswith("FROM "):
            from_model = stripped[5:].strip()
            i += 1
            continue

        if stripped.startswith("SYSTEM "):
            rest = stripped[7:].strip()
            if rest.startswith('"""'):
                # multiline system
                block = [rest[3:]]
                if block[0].endswith('"""') and len(block[0]) >= 3:
                    system = block[0][:-3].strip()
                    i += 1
                    continue
                i += 1
                while i < len(lines):
                    sub = lines[i]
                    if '"""' in sub:
                        idx = sub.index('"""')
                        block.append(sub[:idx])
                        i += 1
                        break
                    block.append(sub)
                    i += 1
                system = "\n".join(block).strip()
                continue
            else:
                system = rest
                i += 1
                continue

        if stripped.startswith("TEMPLATE "):
            rest = stripped[9:].strip()
            if rest.startswith('"""'):
                block = [rest[3:]]
                if block[0].endswith('"""') and len(block[0]) >= 3:
                    template = block[0][:-3].strip()
                    i += 1
                    continue
                i += 1
                while i < len(lines):
                    sub = lines[i]
                    if '"""' in sub:
                        idx = sub.index('"""')
                        block.append(sub[:idx])
                        i += 1
                        break
                    block.append(sub)
                    i += 1
                template = "\n".join(block).strip()
                continue
            else:
                template = rest
                i += 1
                continue

        if stripped.startswith("PARAMETER "):
            parts = stripped[10:].strip().split(maxsplit=1)
            if len(parts) == 2:
                parameters.append((parts[0].strip(), parts[1].strip()))
            i += 1
            continue

        if stripped:
            extra_lines.append(line)
        i += 1

    return {
        "from_model": from_model,
        "system": system,
        "template": template,
        "parameters": parameters,
        "extra": "\n".join(extra_lines).strip(),
    }


class OllamaCreateJob:
    """Executes `ollama create <name> -f <modelfile>` with streaming logs and cancellation."""

    def __init__(
        self,
        name: str,
        modelfile_content: str,
        overwrite: bool = True,
        on_log: Callable[[str], None] | None = None,
        on_progress: Callable[[float, str], None] | None = None,
    ) -> None:
        self.name = name.strip()
        self.modelfile_content = modelfile_content
        self.overwrite = overwrite
        self.on_log = on_log or (lambda msg: None)
        self.on_progress = on_progress or (lambda p, m: None)
        self.proc: subprocess.Popen[str] | None = None
        self._canceled = False

    def cancel(self) -> None:
        self._canceled = True
        if self.proc and self.proc.poll() is None:
            try:
                self.proc.terminate()
            except OSError:
                pass

    def run(self) -> bool:
        """Runs the create command. Returns True if successful, False otherwise."""
        err = validate_ollama_model_name(self.name)
        if err:
            self.on_log(f"エラー: {err}")
            return False

        exe = tools.ollama_exe()
        if exe is None:
            self.on_log("エラー: ollama コマンドが見つかりません。Ollama をインストールしてください。")
            return False

        if not self.overwrite:
            existing = tools.ollama_model_names()
            if existing and self.name.lower() in existing:
                self.on_log(f"エラー: Ollama に同名のモデルがあります: {self.name}（上書きを有効にしてください）")
                return False

        self.on_progress(0.1, "Modelfile 作成中...")
        with tempfile.TemporaryDirectory() as tmpdir:
            mf_path = Path(tmpdir) / "Modelfile"
            mf_path.write_text(self.modelfile_content, encoding="utf-8")
            self.on_log(f"Modelfile を作成しました:\n---\n{self.modelfile_content.strip()}\n---")
            self.on_log(f"実行コマンド: {exe.name} create {self.name} -f {mf_path.name}")
            self.on_progress(0.2, f"ollama create {self.name} 実行中...")

            try:
                self.proc = subprocess.Popen(
                    [str(exe), "create", self.name, "-f", str(mf_path)],
                    cwd=tmpdir,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.STDOUT,
                    text=True,
                    encoding="utf-8",
                    errors="replace",
                    creationflags=tools.CREATE_NO_WINDOW,
                )
            except OSError as e:
                self.on_log(f"プロセス起動失敗: {e}")
                return False

            assert self.proc.stdout is not None
            for line in self.proc.stdout:
                clean_line = re.sub(r"\x1b\[[0-9;?]*[A-Za-z]", "", line).strip()
                if clean_line:
                    self.on_log(clean_line)
                    if "transferring" in clean_line.lower():
                        self.on_progress(0.5, clean_line)
                    elif "parsing" in clean_line.lower():
                        self.on_progress(0.7, clean_line)
                    elif "success" in clean_line.lower():
                        self.on_progress(0.9, clean_line)

            rc = self.proc.wait()
            if self._canceled:
                self.on_log("作成を取り消しました。")
                tools.forget_ollama_cache()
                return False
            if rc != 0:
                self.on_log(f"エラー: ollama create がコード {rc} で終了しました。")
                return False

        tools.forget_ollama_cache()
        self.on_progress(1.0, "モデル作成完了")
        self.on_log(f"モデル '{self.name}' を作成しました！\n使い方: ollama run {self.name}")
        return True
