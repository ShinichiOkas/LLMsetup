"""Tests for ollama_modelfile module."""

import pytest
from llmquant import ollama_modelfile as om


def test_validate_ollama_model_name():
    assert om.validate_ollama_model_name("qwen2.5:7b") is None
    assert om.validate_ollama_model_name("my-model:latest") is None
    assert om.validate_ollama_model_name("custom_model") is None
    assert om.validate_ollama_model_name("user/model:tag") is None

    # Invalid names
    assert om.validate_ollama_model_name("") is not None
    assert om.validate_ollama_model_name("  ") is not None
    assert om.validate_ollama_model_name("Model With Spaces") is not None
    assert om.validate_ollama_model_name("Invalid@Char") is not None


def test_build_modelfile():
    mf = om.build_modelfile(
        from_model="qwen2.5:7b",
        system="You are a helpful coding assistant.",
        parameters=[("temperature", "0.7"), ("num_ctx", "8192")],
        template="{{ .Prompt }}",
        extra="# custom comment",
    )
    assert "FROM qwen2.5:7b" in mf
    assert 'SYSTEM """You are a helpful coding assistant."""' in mf
    assert "PARAMETER temperature 0.7" in mf
    assert "PARAMETER num_ctx 8192" in mf
    assert 'TEMPLATE """{{ .Prompt }}"""' in mf
    assert "# custom comment" in mf


def test_clean_show_modelfile():
    raw_show = (
        '# Modelfile generated by "ollama show"\n'
        '# To build a new Modelfile based on this, replace FROM with:\n'
        '# FROM qwen2.5-coder:7b\n'
        '\n'
        'FROM C:\\Users\\user\\.ollama\\models\\blobs\\sha256-12345\n'
        'TEMPLATE """{{ .Prompt }}"""\n'
        'SYSTEM You are an assistant.\n'
    )
    cleaned = om.clean_show_modelfile(raw_show, "qwen2.5-coder:7b")
    assert "# Modelfile generated" not in cleaned
    assert "FROM qwen2.5-coder:7b" in cleaned
    assert "TEMPLATE" in cleaned
    assert "SYSTEM You are an assistant." in cleaned


def test_parse_modelfile_sections():
    text = (
        'FROM llama3.2:latest\n'
        'SYSTEM """You are a polite bot.\nAlways smile."""\n'
        'PARAMETER temperature 0.5\n'
        'PARAMETER top_p 0.9\n'
        '# Extra comment\n'
    )
    sections = om.parse_modelfile_sections(text)
    assert sections["from_model"] == "llama3.2:latest"
    assert sections["system"] == "You are a polite bot.\nAlways smile."
    assert ("temperature", "0.5") in sections["parameters"]
    assert ("top_p", "0.9") in sections["parameters"]
    assert "# Extra comment" in sections["extra"]
